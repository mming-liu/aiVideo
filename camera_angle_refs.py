def _format_camera_angles() -> str:
    """将运镜视角库格式化为 prompt 可用的文本."""
    sections = []

    # POV
    sections.append("### POV 视角（第一人称代入）")
    for i, angle in enumerate(POV_ANGLES, 1):
        sections.append(f"{i}. {angle}")

    # 鸟瞰
    sections.append("\n### 鸟瞰视角（高空俯拍宏大场景）")
    for i, angle in enumerate(AERIAL_ANGLES, 1):
        sections.append(f"{i}. {angle}")

    # FPV
    sections.append("\n### FPV 视角（穿梭机快速穿越）")
    for i, angle in enumerate(FPV_ANGLES, 1):
        sections.append(f"{i}. {angle}")

    # ACT
    sections.append("\n### ACT 视角（第三人称战斗动作）")
    for i, angle in enumerate(ACT_ANGLES, 1):
        sections.append(f"{i}. {angle}")

    # 关键词库
    sections.append("\n### 通用运镜关键词速查")
    for category, keywords in CAMERA_KEYWORDS.items():
        sections.append(f"- {category}: {keywords}")

    return "\n".join(sections)


def get_camera_angle_for_scene(scene_type: str) -> list[str]:
    """根据场景类型返回推荐的运镜视角.

    Args:
        scene_type: 场景类型 (action/combat/explore/architecture/nature/dialog)

    Returns:
        推荐的运镜视角列表
    """
    scene_mapping = {
        "action": POV_ANGLES[:4],
        "combat": ACT_ANGLES[:4] + POV_ANGLES[2:4],
        "explore": POV_ANGLES[4:] + FPV_ANGLES[:2],
        "architecture": AERIAL_ANGLES[:4],
        "nature": AERIAL_ANGLES[4:] + FPV_ANGLES[4:6],
        "dialog": POV_ANGLES[4:5] + ["中近景 MCU — 胸部以上，表情+肩部动作可见"],
    }
    return scene_mapping.get(scene_type, [])