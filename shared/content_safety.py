def check_chain_safety() -> list[tuple[str, str, str]]:
    """静态检查替换值是否命中其它 key（链式二次替换风险）.

    返回 [(key, value, 命中的其它key), ...]，空 = 安全。
    新增词后应跑一次，保证词表自洽（铁律：value 不得含其它 key）。
    """
    risky = []
    keys = list(SENSITIVE_SUBSTITUTIONS.keys())
    for old, new in SENSITIVE_SUBSTITUTIONS.items():
        for k in keys:
            if k in new and k != old:
                risky.append((old, new, k))
    return risky


